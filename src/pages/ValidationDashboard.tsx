// ValidationDashboard — the /validation route: runs all fixtures through the
// engine + mirrored formulas, renders per-fixture result cards and the
// aggregate metrics (MAE/RMSE/class agreement), and exports CSV + PDF
// evidence for the report. Behind auth (RequireAuth) but not in the main
// nav — it's the academic-evidence surface, not a user feature.

import { useMemo, useState } from "react";
import { FlaskConical, Download, FileText, Loader2 } from "lucide-react";
import {
  runAllFixtures, summarize, type FixtureResult, type ValidationSummary,
} from "@/lib/validation";
import { VALIDATION_FIXTURES } from "@/data/validation-fixtures";
import { jsPDF } from "jspdf";
import {
  BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer,
} from "recharts";
import { CHART_GREEN, CHART_GOLD, CHART_BLUE, CHART_RED, CustomChartTooltip, axisStroke, gridStroke } from "@/components/chart-shared";

/* ── CSV export ── */

function toCsv(results: FixtureResult[], summary: ValidationSummary): string {
  const head = [
    "fixture", "region", "engine_top_crop", "reference_crop", "top_crop_agrees",
    "expected_in_top3", "expected_in_plan", "water_access", "water_band_ok",
    "health_score", "health_band_ok", "engine_class", "reference_class",
    "class_agrees", "engine_score", "reference_score", "abs_error", "build_ms",
  ].join(",");
  const rows = results.map((r) => [
    r.fixtureId, `"${r.region}"`, r.topCrop, r.expectedTopCrop, r.topCropAgrees,
    r.expectedInTop3, r.expectedInPlan, r.waterAccess, r.waterAccessBandOk,
    r.healthScore, r.healthScoreBandOk, r.engineClass, r.referenceClass,
    r.classAgrees, r.engineTopScore.toFixed(3), r.referenceScore.toFixed(3),
    Math.abs(r.engineTopScore - r.referenceScore).toFixed(3), r.buildMs,
  ].join(","));
  const meta = [
    "", `summary,fixtures=${summary.fixtureCount}`,
    `summary,top_crop_agreement_pct=${summary.topCropAgreementPct}`,
    `summary,expected_in_top3_pct=${summary.expectedInTop3Pct}`,
    `summary,class_agreement_pct=${summary.classAgreementPct}`,
    `summary,score_mae=${summary.scoreMae}`,
    `summary,score_rmse=${summary.scoreRmse}`,
    `summary,max_build_ms=${summary.maxBuildMs}`,
  ];
  return [head, ...rows, ...meta].join("\n");
}

/* ── PDF export ── */

function exportPdf(results: FixtureResult[], summary: ValidationSummary) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const width = doc.internal.pageSize.getWidth();
  let y = 20;

  doc.setFontSize(16); doc.setFont("helvetica", "bold");
  doc.text("TerraSuite — Engine Validation Report", 14, y); y += 8;
  doc.setFontSize(9); doc.setFont("helvetica", "normal");
  doc.text("Crop-engine + GEE suitability formulas vs literature-referenced fixtures (FAO GAEZ v4 and cited papers).", 14, y, { maxWidth: width - 28 }); y += 10;

  doc.setFontSize(11); doc.setFont("helvetica", "bold"); doc.text("Aggregate metrics", 14, y); y += 6;
  doc.setFontSize(9); doc.setFont("helvetica", "normal");
  const metricLines = [
    `Fixtures: ${summary.fixtureCount}`,
    `Top-crop agreement: ${summary.topCropAgreementPct.toFixed(0)}%`,
    `Reference crop in engine top-3: ${summary.expectedInTop3Pct.toFixed(0)}%`,
    `Suitability-class agreement (S1-S3/N vs VS/S/MS/N): ${summary.classAgreementPct.toFixed(0)}%`,
    `Score MAE: ${summary.scoreMae} (0-1 scale)`,
    `Score RMSE: ${summary.scoreRmse} (0-1 scale)`,
    `Slowest plan build: ${summary.maxBuildMs} ms (gate: <10 ms)`,
  ];
  metricLines.forEach((l) => { doc.text(l, 18, y); y += 5; });
  y += 4;

  doc.setFontSize(11); doc.setFont("helvetica", "bold"); doc.text("Per-fixture results", 14, y); y += 6;
  for (const r of results) {
    if (y > 262) { doc.addPage(); y = 20; }
    doc.setFontSize(9); doc.setFont("helvetica", "bold");
    doc.text(`${r.fixtureName}`, 14, y); y += 4.5;
    doc.setFontSize(8); doc.setFont("helvetica", "normal");
    const lines = [
      `Engine top crop: ${r.topCrop} (reference: ${r.expectedTopCrop}) — agrees: ${r.topCropAgrees ? "yes" : "no"}`,
      `Class: engine ${r.engineClass} vs reference ${r.referenceClass} — agrees: ${r.classAgrees ? "yes" : "no"}`,
      `Water access ${r.waterAccess}/100 (band ok: ${r.waterAccessBandOk ? "yes" : "no"}) · Health ${r.healthScore}/100 (band ok: ${r.healthScoreBandOk ? "yes" : "no"})`,
      `Score ${r.engineTopScore.toFixed(3)} vs reference ${r.referenceScore.toFixed(3)} · build ${r.buildMs} ms`,
    ];
    lines.forEach((l) => { doc.text(l, 18, y); y += 3.8; });
    y += 2.5;
  }

  if (y > 250) { doc.addPage(); y = 20; }
  doc.setFontSize(8); doc.setTextColor(120);
  doc.text("TerraSuite — generated by the local validation runner. Sources per fixture listed in src/data/validation-fixtures.ts.", 14, y, { maxWidth: width - 28 });
  doc.setTextColor(0);
  doc.save("terrasuite-validation-report.pdf");
}

/* ── Component ── */

export default function ValidationDashboard() {
  const [running, setRunning] = useState(false);
  const [results, setResults] = useState<FixtureResult[] | null>(null);

  const summary = useMemo(() => (results ? summarize(results) : null), [results]);

  const barData = useMemo(() => (results ?? []).map((r) => ({
    name: r.fixtureId.replace("fx-", ""),
    engine: Math.round(r.engineTopScore * 100),
    reference: Math.round(r.referenceScore * 100),
  })), [results]);

  const run = () => {
    setRunning(true);
    // setTimeout lets the spinner paint before the (fast, <50 ms total)
    // synchronous engine run blocks the frame.
    setTimeout(() => {
      setResults(runAllFixtures());
      setRunning(false);
    }, 30);
  };

  return (
    <div className="min-h-screen bg-surface-outer p-6">
      <div className="max-w-4xl mx-auto space-y-6">
        {/* Header */}
        <div className="flex items-center justify-between">
          <h1 className="text-lg font-semibold text-foreground flex items-center gap-2">
            <FlaskConical className="w-5 h-5" /> Engine Validation
          </h1>
          <div className="flex items-center gap-2">
            <button onClick={run} disabled={running}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-primary text-primary-foreground text-xs font-medium disabled:opacity-60">
              {running ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <FlaskConical className="w-3.5 h-3.5" />}
              {running ? "Running fixtures…" : "Run validation"}
            </button>
            {results && (
              <>
                <button onClick={() => {
                  const csv = toCsv(results, summarize(results));
                  const blob = new Blob([csv], { type: "text/csv" });
                  const url = URL.createObjectURL(blob);
                  const a = document.createElement("a");
                  a.href = url; a.download = "terrasuite-validation.csv"; a.click();
                  URL.revokeObjectURL(url);
                }}
                  className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-border text-xs text-foreground hover:bg-accent transition-colors">
                  <Download className="w-3.5 h-3.5" /> CSV
                </button>
                <button onClick={() => exportPdf(results, summarize(results))}
                  className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-border text-xs text-foreground hover:bg-accent transition-colors">
                  <FileText className="w-3.5 h-3.5" /> PDF
                </button>
              </>
            )}
          </div>
        </div>

        {!results && !running && (
          <div className="rounded-xl border border-border bg-card p-6 text-sm text-muted-foreground space-y-3">
            <p>
              Runs the {VALIDATION_FIXTURES.length} literature-referenced fixtures (FAO GAEZ v4 + cited papers)
              through the production crop engine and the pinned GEE suitability / NDVI health formulas,
              then computes agreement metrics (top-crop agreement, class agreement, MAE/RMSE).
            </p>
            <p className="text-xs">
              Evidence surface for the report's evaluation chapter — not a user-facing feature.
              Fixture sources: {VALIDATION_FIXTURES.map((f) => f.region.split(",").pop()?.trim()).join(" · ")}.
            </p>
          </div>
        )}

        {summary && (
          <>
            {/* Metric strip */}
            <div className="grid grid-cols-2 md:grid-cols-4 gap-3">
              {[
                { label: "Top-crop agreement", value: `${summary.topCropAgreementPct.toFixed(0)}%`, color: CHART_GREEN },
                { label: "In top-3", value: `${summary.expectedInTop3Pct.toFixed(0)}%`, color: CHART_BLUE },
                { label: "Class agreement", value: `${summary.classAgreementPct.toFixed(0)}%`, color: CHART_GOLD },
                { label: `MAE ${summary.scoreMae} / RMSE ${summary.scoreRmse}`, value: `≤10 ms: ${summary.allWithinPerfGate ? "pass" : "fail"}`, color: summary.allWithinPerfGate ? CHART_GREEN : CHART_RED },
              ].map((m) => (
                <div key={m.label} className="p-3 rounded-xl border border-border bg-card space-y-1">
                  <div className="text-[10px] text-muted-foreground">{m.label}</div>
                  <div className="text-sm font-semibold" style={{ color: m.color }}>{m.value}</div>
                </div>
              ))}
            </div>

            {/* Score comparison chart */}
            <div className="rounded-xl border border-border bg-card p-4">
              <h3 className="text-xs font-medium text-foreground mb-3">Engine vs reference score (0–100)</h3>
              <div className="h-56">
                <ResponsiveContainer width="100%" height="100%">
                  <BarChart data={barData}>
                    <CartesianGrid stroke={gridStroke} strokeDasharray="3 3" />
                    <XAxis dataKey="name" tick={{ fill: axisStroke, fontSize: 9 }} />
                    <YAxis domain={[0, 100]} tick={{ fill: axisStroke, fontSize: 9 }} />
                    <Tooltip content={<CustomChartTooltip />} />
                    <Bar dataKey="engine" name="Engine" fill={CHART_GREEN} radius={[2, 2, 0, 0]} />
                    <Bar dataKey="reference" name="Reference" fill={CHART_GOLD} radius={[2, 2, 0, 0]} />
                  </BarChart>
                </ResponsiveContainer>
              </div>
            </div>

            {/* Fixture cards */}
            <div className="space-y-3">
              {results.map((r) => (
                <div key={r.fixtureId} className="rounded-xl border border-border bg-card p-4">
                  <div className="flex items-center justify-between mb-2">
                    <div>
                      <div className="text-sm font-medium text-foreground">{r.fixtureName}</div>
                      <div className="text-[10px] text-muted-foreground">{r.region}</div>
                    </div>
                    <div className="flex items-center gap-1.5 text-[10px]">
                      {r.topCropAgrees
                        ? <span className="px-1.5 py-0.5 rounded-full bg-[#7BC75B]/20 text-[#7BC75B] font-medium">top crop ✓</span>
                        : <span className="px-1.5 py-0.5 rounded-full bg-[#d73027]/20 text-[#d73027] font-medium">top crop ✗</span>}
                      {r.classAgrees
                        ? <span className="px-1.5 py-0.5 rounded-full bg-[#7BC75B]/20 text-[#7BC75B] font-medium">class ✓</span>
                        : <span className="px-1.5 py-0.5 rounded-full bg-[#d73027]/20 text-[#d73027] font-medium">class ✗</span>}
                    </div>
                  </div>
                  <div className="grid grid-cols-2 md:grid-cols-4 gap-2 text-[11px]">
                    <div className="p-2 rounded-lg bg-accent/15">
                      <span className="text-muted-foreground">Top crop </span>
                      <span className="text-foreground font-medium">{r.topCrop}</span>
                    </div>
                    <div className="p-2 rounded-lg bg-accent/15">
                      <span className="text-muted-foreground">Water access </span>
                      <span className="text-foreground font-medium">{r.waterAccess}/100</span>
                    </div>
                    <div className="p-2 rounded-lg bg-accent/15">
                      <span className="text-muted-foreground">Health </span>
                      <span className="text-foreground font-medium">{r.healthScore}/100</span>
                    </div>
                    <div className="p-2 rounded-lg bg-accent/15">
                      <span className="text-muted-foreground">Build </span>
                      <span className="text-foreground font-medium">{r.buildMs} ms</span>
                    </div>
                  </div>
                </div>
              ))}
            </div>
          </>
        )}
      </div>
    </div>
  );
}
